import { copyFile, cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

// Canonical source is one Skill directory; keep its relative references intact.
const root = new URL("../", import.meta.url);
const skill = await readFile(new URL("skills/coflow/SKILL.md", root), "utf8");
const version = skill.match(/^  version: "(\d+\.\d+\.\d+)"$/m)?.[1];
if (!version)
  throw new Error("CoFlow Skill requires a stable semantic metadata.version");
await writeFile(
  new URL("apps/web/lib/skill-version.ts", root),
  `// Generated by scripts/sync-agent-assets.mjs from the canonical Skill.\nexport const coflowSkillVersion = ${JSON.stringify(version)};\n`,
);
const destination = new URL("apps/web/public/agent/coflow/", root);
await mkdir(destination, { recursive: true });
await cp(new URL("skills/coflow/", root), destination, { recursive: true });
console.log(
  `Published ${fileURLToPath(destination).replace(fileURLToPath(root), "")}`,
);
await copyFile(
  new URL("docs/openapi.yaml", root),
  new URL("../openapi.yaml", destination),
);
// Existing installed prompts can discover the new entry without a second Skill.
for (const legacy of ["coflow-report", "coflow-todo"]) {
  const directory = new URL(`../${legacy}/`, destination);
  await rm(directory, { recursive: true, force: true });
  await mkdir(directory, { recursive: true });
  await writeFile(
    new URL("SKILL.md", directory),
    "# CoFlow integration moved\n\nRead the single [CoFlow Skill](../coflow/SKILL.md). It links installation, Timeline reporting and Todo instructions as needed. Reuse your existing private credential and project binding; do not install a second Skill or create another token merely for this update.\n",
  );
}
